/// Test observations are bounded metadata, not a recording of terminal content.
#[cfg(test)]
#[derive(Clone)]
pub struct EchoObservation {
    input_bytes: Arc<AtomicU64>,
    reply_bytes: Arc<AtomicU64>,
    last_reply: watch::Receiver<Vec<u8>>,
}
#[cfg(test)]
impl EchoObservation {
    /// Number of user input bytes processed by the echo driver.
    pub fn input_bytes(&self) -> u64 {
        self.input_bytes.load(Ordering::SeqCst)
    }
    /// Number of backend reply bytes consumed upstream by the driver.
    pub fn reply_bytes(&self) -> u64 {
        self.reply_bytes.load(Ordering::SeqCst)
    }
    /// Most recent backend reply; at most MAX_CHUNK bytes.
    pub fn last_reply(&self) -> Vec<u8> {
        self.last_reply.borrow().clone()
    }
}
/// Synthetic transport for actor tests: user input becomes output; authoritative
/// replies are observed upstream and are not fed back as new program output.
#[cfg(test)]
pub struct EchoTransport;
#[cfg(test)]
impl EchoTransport {
    /// Spawn bounded input/output channels and a cooperatively cancelled driver.
    /// Must be called inside a Tokio runtime.
    pub fn spawn() -> (ChannelTransport, EchoObservation) {
        let (input, mut commands) = mpsc::channel(QUEUE);
        let (output, receiver) = mpsc::channel(QUEUE);
        let (stop, mut stopping) = watch::channel(false);
        let (last, last_reply) = watch::channel(vec![]);
        let input_bytes = Arc::new(AtomicU64::new(0));
        let reply_bytes = Arc::new(AtomicU64::new(0));
        let observation = EchoObservation {
            input_bytes: input_bytes.clone(),
            reply_bytes: reply_bytes.clone(),
            last_reply,
        };
        let task = tokio::spawn(async move {
            loop {
                tokio::select! {
                    biased;
                    _ = stopping.changed() => break,
                    command = commands.recv() => match command {
                        None => break,
                        Some(TransportWrite::Input(bytes)) => {
                            let count = bytes.len() as u64;
                            tokio::select! { biased;
                                _ = stopping.changed() => break,
                                result = output.send(bytes) => { if result.is_err() { break; } }
                            }
                            input_bytes.fetch_add(count, Ordering::SeqCst);
                        }
                        Some(TransportWrite::Resize(_,reply))=>{let _=reply.send(Ok(()));}
                        Some(TransportWrite::Reply(bytes)) => {
                            reply_bytes.fetch_add(bytes.len() as u64, Ordering::SeqCst);
                            last.send_replace(bytes);
                        }
                    }
                }
            }
        });
        (
            ChannelTransport {
                output: receiver,
                input,
                stop,
                task: Some(task),
                failed: None,
            },
            observation,
        )
    }
}
/// Owned bounded endpoints for a supervised blocking/native transport driver.
/// Native teardown must continue even after async endpoint cancellation.
pub struct DriverEndpoint {
    /// Maximum QUEUE chunks; MAX_CHUNK bytes per entry enforced by actor.
    pub output: mpsc::Sender<Vec<u8>>,
    /// Bounded input, query replies and native resize requests.
    pub input: mpsc::Receiver<TransportWrite>,
    /// Out-of-band cancellation, independent of command admission.
    pub stop: watch::Receiver<bool>,
    /// Set true for fatal native I/O failures.
    pub failed: watch::Sender<bool>,
}
impl ChannelTransport {
    /// Fixed-capacity endpoints, without starting native I/O tasks.
    pub fn bounded_driver() -> (Self, DriverEndpoint) {
        let (output, receiver) = mpsc::channel(QUEUE);
        let (input, commands) = mpsc::channel(QUEUE);
        let (stop, stopping) = watch::channel(false);
        let (failed, failure) = watch::channel(false);
        (
            Self {
                output: receiver,
                input,
                stop,
                task: None,
                failed: Some(failure),
            },
            DriverEndpoint {
                output,
                input: commands,
                stop: stopping,
                failed,
            },
        )
    }
}
impl Drop for ChannelTransport {
    fn drop(&mut self) {
        self.stop.send_replace(true);
        if let Some(task) = self.task.take() {
            task.abort();
        } // Native cleanup is separately supervised.
    }
}

/// Cloneable control handle. Dropping a view does not close it: callers keep the
/// handle in the session registry. Dropping the last handle is explicit abandonment.
#[derive(Clone)]
pub struct SessionHandle {
    commands: mpsc::Sender<Command>,
    cancel: watch::Sender<bool>,
    /// Coarse state subscription. Cloning this receiver is not an ownership lease.
    pub state: watch::Receiver<SessionState>,
}
impl SessionHandle {
    /// Compare backend actor identity for trusted registrars; not an authorization
    /// capability. Independent of publicly replaceable watch receivers.
    pub fn same_actor(&self, other: &Self) -> bool {
        self.commands.same_channel(&other.commands)
    }
    /// Capture replay and install its bounded live subscriber atomically. Diagnostic
    /// single-lease API: not a production attach authorization or renderer binding.
    /// Full output queues pause parsing/transport; controls and close remain fair.
    /// Geometry/control changes end this lease and require a new generation.
    pub async fn diagnostic_subscribe(
        &self,
        rows: usize,
        history_budget: usize,
        restore_budget: usize,
    ) -> Result<SessionStream, SessionRestoreError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Subscribe {
            history_rows: rows.min(crate::MAX_RECENT_ROWS),
            history_budget: history_budget.min(MAX_HISTORY_BYTES),
            restore_budget: restore_budget.min(MAX_RESTORE_BYTES),
            reply,
        })?;
        let installed = result.await.map_err(|_| SessionError::Closed)??;
        installed
            .committed
            .await
            .map_err(|_| SessionError::Closed)?;
        Ok(installed.stream)
    }
}
impl SessionHandle {
    /// Compare and capture a precise screen repair on one actor turn, never clearing risk.
    pub async fn diagnostic_repair(
        &self,
        request: SessionRepairRequest,
    ) -> Result<RepairAdmission, SessionRestoreError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Repair { request, reply })?;
        result
            .await
            .map_err(|_| SessionRestoreError::Session(SessionError::Closed))?
    }
    /// Admit a read-only marker into THIS lease's bounded ordered output queue.
    /// Success is not delivery or ACK. Full queue returns Busy without waiting;
    /// cancelled requests and stale serials never inject a marker into a new lease.
    pub async fn diagnostic_marker(&self, lease_id: u64) -> Result<(), SessionError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Marker(lease_id, reply))?;
        result.await.map_err(|_| SessionError::Closed)?
    }
    /// Try bounded command admission, then wait for actor acceptance. Input may be
    /// cancelled later on explicit close; success is NOT a physical-write receipt.
    pub async fn input(&self, bytes: Vec<u8>) -> Result<(), SessionError> {
        if bytes.len() > MAX_CHUNK {
            return Err(SessionError::ChunkTooLarge);
        }
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Input(bytes, reply))?;
        result.await.map_err(|_| SessionError::Closed)?
    }
    /// Viewer input, validated against the current lease on the actor turn.
    /// Success is queue admission, not a physical native write; admitted input
    /// cannot be undone on subsequent detach. Caller cancellation before admission rejects.
    pub async fn input_for_lease(
        &self,
        lease_id: u64,
        cancelled: watch::Receiver<bool>,
        bytes: Vec<u8>,
    ) -> Result<(), SessionError> {
        if bytes.is_empty() || bytes.len() > MAX_CHUNK {
            return Err(SessionError::ChunkTooLarge);
        }
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::BoundInput {
            lease_id,
            cancelled,
            bytes,
            reply,
        })?;
        result.await.map_err(|_| SessionError::Closed)?
    }

    /// Viewer geometry is authorized against its lease on the actor turn.
    /// Native ACK, not frontend optimistic resize, commits dimensions and revokes
    /// the lease. Cancellation after native admission cannot undo a physical resize.
    pub async fn resize_for_lease(
        &self,
        lease_id: u64,
        cancelled: watch::Receiver<bool>,
        size: TermSize,
    ) -> Result<(), SessionError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::BoundResize {
            lease_id,
            cancelled,
            size,
            reply,
        })?;
        result.await.map_err(|_| SessionError::Closed)?
    }

    /// Request native resize; parser dimensions advance only after driver ACK.
    /// An unacknowledged resize fails and closes the session after five seconds.
    pub async fn resize(&self, size: TermSize) -> Result<(), SessionError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Resize(size, reply))?;
        result.await.map_err(|_| SessionError::Closed)?
    }
    /// Serialize a UI palette update with output handling; remote OSC overrides
    /// keep precedence until the program resets them.
    pub async fn set_query_palette(
        &self,
        palette: crate::QueryPalette,
    ) -> Result<(), SessionError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Palette(palette, reply))?;
        result.await.map_err(|_| SessionError::Closed)?
    }
    /// Set measured cell geometry, or None when no renderer reports it.
    pub async fn set_cell_pixels(&self, pixels: Option<(u16, u16)>) -> Result<(), SessionError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::CellPixels(pixels, reply))?;
        result.await.map_err(|_| SessionError::Closed)?
    }
    /// Request a bounded, non-approximate diagnostic restore at the actor's
    /// serialization point. Not an output delivery/ACK receipt or attach snapshot.
    /// Dropped requests are skipped when possible; callers own concurrent limits.
    pub async fn diagnostic_restore(
        &self,
        byte_budget: usize,
    ) -> Result<SessionRestore, SessionRestoreError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Restore(byte_budget.min(MAX_RESTORE_BYTES), reply))?;
        result
            .await
            .map_err(|_| SessionRestoreError::Session(SessionError::Closed))?
    }
    /// Capture bounded recent history and a screen-only replay in one command.
    /// The driver must freeze/retain output after boundary.parsed_bytes until it
    /// sends Commit; this method alone does not provide a live subscription.
    pub async fn diagnostic_bootstrap(
        &self,
        history_rows: usize,
        history_budget: usize,
        restore_budget: usize,
    ) -> Result<SessionBootstrap, SessionRestoreError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Bootstrap {
            history_rows: history_rows.min(crate::MAX_RECENT_ROWS),
            history_budget: history_budget.min(MAX_HISTORY_BYTES),
            restore_budget: restore_budget.min(MAX_RESTORE_BYTES),
            reply,
        })?;
        result
            .await
            .map_err(|_| SessionRestoreError::Session(SessionError::Closed))?
    }
    /// Capture a visible checksum at the actor boundary. Do not poll on every frame.
    pub async fn diagnostic_digest(&self) -> Result<SessionDigest, SessionError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Digest(reply))?;
        result.await.map_err(|_| SessionError::Closed)
    }
    /// Confirm only at the identical actor boundary. Binding generation must be
    /// validated by the view driver before calling; this is not a lease protocol.
    pub async fn verify_screen(
        &self,
        boundary: SessionState,
        digest: String,
    ) -> Result<ScreenVerification, SessionError> {
        if digest.len() != 16
            || !digest
                .bytes()
                .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
        {
            return Err(SessionError::InvalidDigest);
        }
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Verify(boundary, digest, reply))?;
        result.await.map_err(|_| SessionError::Closed)
    }
    /// Return a visible-screen diagnostic, never a complete restore snapshot.
    pub async fn inspect(&self) -> Result<ObservedScreen, SessionError> {
        let (reply, result) = oneshot::channel();
        self.enqueue(Command::Inspect(reply))?;
        result.await.map_err(|_| SessionError::Closed)
    }
    fn enqueue(&self, command: Command) -> Result<(), SessionError> {
        if self.state.borrow().lifecycle != Lifecycle::Running {
            return Err(SessionError::Closed);
        }
        self.commands
            .try_send(command)
            .map_err(|error| match error {
                mpsc::error::TrySendError::Full(_) => SessionError::Busy,
                mpsc::error::TrySendError::Closed(_) => SessionError::Closed,
            })
    }
    /// Out-of-band cancellation is not queued behind data or inspect requests.
    pub fn close(&self) {
        self.cancel.send_replace(true);
    }
}
/// Supervision receipt; do not abort it to close a session. Use SessionHandle::close.
/// Join completion means the synthetic transport driver was also joined.
pub struct SessionTask(JoinHandle<(SessionState, ObservedScreen)>);
impl SessionTask {
    /// Wait for the actor and driver to exit. Apply an application-owned deadline.
    pub async fn join(self) -> Result<SessionState, tokio::task::JoinError> {
        self.0.await.map(|(state, _screen)| state)
    }
    /// Diagnostic final visible screen, including EOF replacement characters.
    /// This does not contain full restore modes or historical state.
    pub async fn join_with_screen(
        self,
    ) -> Result<(SessionState, ObservedScreen), tokio::task::JoinError> {
        self.0.await
    }
}
/// Spawn one owner of parser/grid state. No shared Mutex<Term>, no GUI references.
/// Uses the existing probe parser, so snapshot/OSC/color limitations still apply.
pub fn spawn_session(
    size: TermSize,
    history: usize,
    transport: ChannelTransport,
) -> (SessionHandle, SessionTask) {
    spawn_inner(size, history, transport, encoding::Mode::Utf8)
}
/// Validation-only already-classified GBK text. No production binary classifier.
#[cfg(feature = "validation")]
pub fn spawn_gbk_text_session(
    size: TermSize,
    history: usize,
    transport: ChannelTransport,
) -> (SessionHandle, SessionTask) {
    spawn_inner(size, history, transport, encoding::Mode::Gbk)
}
fn spawn_inner(
    size: TermSize,
    history: usize,
    mut transport: ChannelTransport,
    mode: encoding::Mode,
) -> (SessionHandle, SessionTask) {
    let (commands, mut receiver) = mpsc::channel(QUEUE);
    let (cancel, mut cancelled) = watch::channel(false);
    let initial = SessionState {
        lifecycle: Lifecycle::Running,
        size,
        parsed_bytes: 0,
        utf8_bytes: 0,
        source_is_utf8: mode.source_is_utf8(),
        revision: 0,
    };
    let (state, subscription) = watch::channel(initial.clone());
    let handle = SessionHandle {
        commands,
        cancel,
        state: subscription,
    };
    let task = tokio::spawn(async move {
        let mut terminal = TerminalProbe::new(size, history);
        let mut decoder = encoding::Decoder::new(mode);
        let mut current = initial;
        let mut replies = VecDeque::<Vec<u8>>::new();
        let mut reply_bytes = 0;
        let mut resizing: Option<PendingResize> = None;
        let mut lease: Option<stream::Lease> = None;
        let mut stream_permit: Option<mpsc::OwnedPermit<StreamRecord>> = None;
        let mut lease_serial = 0u64;
        loop {
            // Check cancellation before each bounded processing turn, then use
            // fair selection so sustained output cannot starve resize/inspect.
            if *cancelled.borrow() || cancelled.has_changed().is_err() {
                current.lifecycle = Lifecycle::Closed;
                break;
            }
            let stream_sender = lease.as_ref().map(|lease| lease.output.clone());
            let closing_sender = stream_sender.clone();
            let sync_deadline = terminal.sync_deadline();
            let resize_deadline = resizing.as_ref().map(|pending| pending.deadline);
            tokio::select! {
                _=async {match closing_sender {Some(sender)=>sender.closed().await,None=>std::future::pending().await}}, if lease.is_some()=>{
                    stream::invalidate(&mut lease,&mut stream_permit,StreamEnd::Detached,&current);
                }
                slot=async {match stream_sender {Some(sender)=>sender.reserve_owned().await,None=>std::future::pending().await}}, if lease.is_some() && stream_permit.is_none()=>{
                    match slot {Ok(slot)=>stream_permit=Some(slot),Err(_)=>stream::invalidate(&mut lease,&mut stream_permit,StreamEnd::Detached,&current)}
                }
                failure=async {match &mut transport.failed{Some(failed)=>failed.changed().await, None=>std::future::pending().await}}=>{
                  if transport.failed.as_ref().is_some_and(|f|*f.borrow()){current.lifecycle=Lifecycle::Failed;break;}
                  if failure.is_err(){transport.failed=None;}
                }
                native=async {match &mut resizing{Some(pending)=>(&mut pending.native).await, None=>std::future::pending().await}}=>{
                    if let Some(PendingResize{size,reply,..})=resizing.take(){let result=native.unwrap_or(Err(SessionError::Transport));if result.is_ok(){terminal.resize(size);current.size=size;current.revision+=1;state.send_replace(current.clone());stream::invalidate(&mut lease,&mut stream_permit,StreamEnd::Reconfigured,&current);}let _=reply.send(result);}
                }
                _=async {match resize_deadline{Some(deadline)=>tokio::time::sleep_until(deadline).await,None=>std::future::pending().await}}=>{
                    if let Some(pending)=resizing.take(){let _=pending.reply.send(Err(SessionError::Transport));}
                    current.lifecycle=Lifecycle::Failed;break;
                }
                _ = async {
                    match sync_deadline {
                        Some(deadline) => tokio::time::sleep_until(deadline.into()).await,
                        None => std::future::pending::<()>().await,
                    }
                }, if lease.is_none() || stream_permit.is_some() => {
                    if terminal.expire_sync(std::time::Instant::now()) {
                        if !queue_replies(&mut terminal, &mut replies, &mut reply_bytes,mode) { current.lifecycle = Lifecycle::Failed; break; }
                        current.revision += 1; state.send_replace(current.clone());
                        if let Some(permit)=stream_permit.take(){permit.send(StreamRecord::Fence(current.clone()));}
                    }
                }
                _ = cancelled.changed() => { current.lifecycle = Lifecycle::Closed; break; }
                permit = transport.input.reserve(), if !replies.is_empty() => {
                    match permit {
                        Ok(permit) => {
                            if let Some(reply) = replies.pop_front() {
                                reply_bytes -= reply.len(); permit.send(TransportWrite::Reply(reply));
                            }
                        }
                        Err(_) => { current.lifecycle = Lifecycle::Failed; break; }
                    }
                }
                // Output remains readable while flushing replies so a driver stuck
                // behind its output queue cannot deadlock against input pressure.
                output = decoder.next(&mut transport.output), if resizing.is_none() && (lease.is_none() || stream_permit.is_some()) => {
                    match output {
                        Some(Ok((bytes,source_count))) => {
                            let start=current.utf8_bytes;
                            let Some(source_after)=current.parsed_bytes.checked_add(source_count)else{current.lifecycle=Lifecycle::Failed;break;};
                            let Some(utf8_after)=current.utf8_bytes.checked_add(bytes.len() as u64)else{current.lifecycle=Lifecycle::Failed;break;};
                            terminal.feed(&bytes);
                            current.parsed_bytes=source_after;current.utf8_bytes=utf8_after;
                            if !queue_replies(&mut terminal, &mut replies, &mut reply_bytes,mode) { current.lifecycle = Lifecycle::Failed; break; }
                            current.revision += 1; state.send_replace(current.clone());
                            if let Some(permit)=stream_permit.take(){if bytes.is_empty(){permit.send(StreamRecord::Marker(current.clone()));}else{permit.send(StreamRecord::Data {start,bytes,boundary:current.clone()});}}
                        }
                        Some(_) => { current.lifecycle = Lifecycle::Failed; break; }
                        None => {
                            terminal.finish_input();
                            let bounded = queue_replies(&mut terminal, &mut replies, &mut reply_bytes,mode);
                            // At EOF an outstanding upstream reply cannot be acknowledged
                            // by this channel driver; fail explicitly rather than discard.
                            current.lifecycle = if decoder.finish() && bounded && replies.is_empty() && !transport.failed.as_ref().is_some_and(|f|*f.borrow()) { Lifecycle::Ended } else { Lifecycle::Failed };
                            break;
                        }
                    }
                }
                command = receiver.recv() => match command {
                    None => { current.lifecycle = Lifecycle::Closed; break; }
                    Some(Command::Input(bytes, reply)) => {
                        let result = if !replies.is_empty() { Err(SessionError::Busy) } else {
                            mode.encode(bytes).and_then(|bytes|transport.input.try_send(TransportWrite::Input(bytes)).map_err(|error| match error {
                                mpsc::error::TrySendError::Full(_) => SessionError::Busy,
                                mpsc::error::TrySendError::Closed(_) => SessionError::Transport,
                            }))
                        };
                        let _ = reply.send(result);
                    }
                    Some(Command::BoundInput{lease_id,cancelled,bytes,reply})=>{
                        let result=if reply.is_closed()||*cancelled.borrow()||cancelled.has_changed().is_err()||lease.as_ref().is_none_or(|l|l.id!=lease_id||l.output.is_closed()){
                            Err(SessionError::StaleLease)
                        }else if !replies.is_empty()||resizing.is_some(){Err(SessionError::Busy)}else{
                            mode.encode(bytes).and_then(|bytes|transport.input.try_send(TransportWrite::Input(bytes)).map_err(|e|match e{mpsc::error::TrySendError::Full(_)=>SessionError::Busy,mpsc::error::TrySendError::Closed(_)=>SessionError::Transport}))
                        };let _=reply.send(result);
                    }

                    Some(Command::BoundResize{lease_id,cancelled,size,reply})=>{
                        if reply.is_closed()||*cancelled.borrow()||cancelled.has_changed().is_err()||lease.as_ref().is_none_or(|l|l.id!=lease_id||l.output.is_closed()){
                            let _=reply.send(Err(SessionError::StaleLease));
                        }else if resizing.is_some(){let _=reply.send(Err(SessionError::Busy));}
                        else if size==current.size{let _=reply.send(Ok(()));}
                        else{let(sent,native)=oneshot::channel();match transport.input.try_send(TransportWrite::Resize(size,sent)){
                            Ok(())=>resizing=Some(PendingResize{size,reply,native,deadline:tokio::time::Instant::now()+std::time::Duration::from_secs(5)}),
                            Err(mpsc::error::TrySendError::Full(_))=>{let _=reply.send(Err(SessionError::Busy));},
                            Err(mpsc::error::TrySendError::Closed(_))=>{let _=reply.send(Err(SessionError::Transport));},
                        }}
                    }

                    Some(Command::Resize(size, reply)) => {
                        if resizing.is_some(){let _=reply.send(Err(SessionError::Busy));}else{
                          let(sent,native)=oneshot::channel();
                          match transport.input.try_send(TransportWrite::Resize(size,sent)){
                            Ok(())=>resizing=Some(PendingResize{size,reply,native,deadline:tokio::time::Instant::now()+std::time::Duration::from_secs(5)}),
                            Err(mpsc::error::TrySendError::Full(_))=>{let _=reply.send(Err(SessionError::Busy));},
                            Err(mpsc::error::TrySendError::Closed(_))=>{let _=reply.send(Err(SessionError::Transport));},
                          }
                        }
                    }
                    Some(Command::Palette(palette, reply)) => {
                        terminal.set_query_palette(palette); current.revision += 1;
                        state.send_replace(current.clone()); stream::invalidate(&mut lease,&mut stream_permit,StreamEnd::Reconfigured,&current); let _ = reply.send(Ok(()));
                    }
                    Some(Command::CellPixels(pixels, reply)) => {
                        terminal.set_cell_pixels(pixels); current.revision += 1;
                        state.send_replace(current.clone()); stream::invalidate(&mut lease,&mut stream_permit,StreamEnd::Reconfigured,&current); let _ = reply.send(Ok(()));
                    }
                    Some(Command::Restore(limit, reply)) => {
                        if !reply.is_closed() {
                            let result = terminal.restore_sequence_bounded(limit)
                                .map_err(SessionRestoreError::Gap)
                                .and_then(|restore| {
                                    if !restore.approximations.is_empty() { return Err(SessionRestoreError::Approximate(restore.approximations)); }
                                    Ok(SessionRestore { boundary: current.clone(), bytes: restore.bytes })
                                });
                            let _ = reply.send(result);
                        }
                    }
                    Some(Command::Subscribe{history_rows,history_budget,restore_budget,reply})=>{
                        if !reply.is_closed(){
                            let result=if resizing.is_some(){Err(SessionRestoreError::Session(SessionError::Busy))}else{stream::prepare(&terminal,&current,history_rows,history_budget,restore_budget)};
                            match result{
                                Err(error)=>{let _=reply.send(Err(error));},
                                Ok(bootstrap)=>match lease_serial.checked_add(1){
                                    None=>{let _=reply.send(Err(SessionError::LeaseExhausted.into()));},
                                    Some(next)=>{
                                        let(new,view)=stream::create(next,bootstrap);
                                        // A cancelled/failed request must not revoke a healthy old lease.
                                        let(sent,committed)=oneshot::channel();
                                        if reply.send(Ok(InstalledStream{stream:view,committed})).is_ok(){
                                            stream::invalidate(&mut lease,&mut stream_permit,StreamEnd::Replaced,&current);
                                            lease=Some(new);lease_serial=next;
                                            let _=sent.send(());
                                        }
                                    }
                                }
                            }
                        }
                    }
                    Some(Command::Bootstrap { history_rows, history_budget, restore_budget, reply }) => {
                        if !reply.is_closed() {
                            let result=stream::prepare(&terminal,&current,history_rows,history_budget,restore_budget);
                            let _ = reply.send(result);
                        }
                    }
                    Some(Command::Repair {request, reply}) => {
                        if !reply.is_closed() {
                            let result = (|| -> Result<RepairAdmission,SessionRestoreError> {
                                if *request.cancelled.borrow() || !lease.as_ref().is_some_and(|l|l.id==request.lease_id && !l.output.is_closed()) {
                                    return Err(SessionError::StaleLease.into());
                                }
                                if request.boundary != current { return Ok(RepairAdmission::Stale); }
                                if request.digest.len()!=16 || !request.digest.bytes().all(|b|b.is_ascii_digit()||(b'a'..=b'f').contains(&b)) { return Err(SessionError::InvalidDigest.into()); }
                                if resizing.is_some() { return Err(SessionError::Busy.into()); }
                                if request.digest==terminal.screen_digest() { return Ok(RepairAdmission::Equal); }
                                let active=lease.as_ref().ok_or(SessionError::StaleLease)?;
                                let hold=active.repair.clone().try_acquire_owned().map_err(|_|SessionError::Busy)?;
                                let slot=match stream_permit.take(){Some(slot)=>slot,None=>active.output.clone().try_reserve_owned().map_err(|e| match e { mpsc::error::TrySendError::Full(_)=>SessionError::Busy,mpsc::error::TrySendError::Closed(_)=>SessionError::StaleLease })?};
                                let restore=terminal.repair_screen_bounded(MAX_RESTORE_BYTES).map_err(SessionRestoreError::Gap)?;
                                if !restore.approximations.is_empty() { return Err(SessionRestoreError::Approximate(restore.approximations)); }
                                if *request.cancelled.borrow() || reply.is_closed() { return Err(SessionError::StaleLease.into()); }
                                slot.send(StreamRecord::Repair {boundary:current.clone(),bytes:restore.bytes,hold:Some(hold)});
                                Ok(RepairAdmission::Queued)
                            })();
                            let _=reply.send(result);
                        }
                    }
                    Some(Command::Marker(id,reply)) => {
                        if !reply.is_closed() {
                            let result = match lease.as_ref().filter(|l| l.id == id && !l.output.is_closed()) {
                                None => Err(SessionError::StaleLease),
                                Some(_) if resizing.is_some() || terminal.sync_deadline().is_some() => Err(SessionError::Busy),
                                Some(current_lease) => {
                                    let slot = match stream_permit.take() {
                                        Some(slot) => Ok(slot),
                                        None => current_lease.output.clone().try_reserve_owned().map_err(|e| match e {
                                            mpsc::error::TrySendError::Full(_) => SessionError::Busy,
                                            mpsc::error::TrySendError::Closed(_) => SessionError::StaleLease,
                                        }),
                                    };
                                    slot.map(|slot| { slot.send(StreamRecord::Marker(current.clone())); })
                                }
                            };
                            let _ = reply.send(result);
                        }
                    }
                    Some(Command::ShellMarkers { lease_id, cancelled, reply }) => {
                        if !reply.is_closed() {
                            let result = if *cancelled.borrow()
                                || lease.as_ref().is_none_or(|l| l.id != lease_id || l.output.is_closed()) {
                                Err(SessionError::StaleLease)
                            } else {
                                Ok(SessionShellMarkers { sampled_at: current.clone(), hints: terminal.take_shell_markers() })
                            };
                            shell::deliver(&mut terminal, reply, result);
                        }
                    }
                    Some(Command::Digest(reply)) => {
                        if !reply.is_closed(){ let _=reply.send(SessionDigest{boundary:current.clone(),risk:terminal.divergence_risk(),digest:terminal.screen_digest()}); }
                    }
                    Some(Command::Verify(boundary,digest,reply)) => {
                        if !reply.is_closed(){
                            let result=if boundary!=current {ScreenVerification::Stale}
                            else if digest!=terminal.screen_digest(){ScreenVerification::Mismatch}
                            else {terminal.side.risk=0;terminal.ground.rep_seen=false;ScreenVerification::Equal};
                            let _=reply.send(result);
                        }
                    }
                    Some(Command::Inspect(reply)) => { let _ = reply.send(terminal.screen()); }
                }
            }
        }
        // Discard only on declared cancellation/failure. EOF has already been
        // finalized. No attempt to disguise lost pending data as a normal end.
        transport.stop.send_replace(true);
        // The test driver always awaits on cancellable channels, not OS I/O.
        if let Some(task) = transport.task.take() {
            let _ = task.await;
        }
        current.revision += 1;
        state.send_replace(current.clone());
        stream::invalidate(
            &mut lease,
            &mut stream_permit,
            StreamEnd::Session(current.lifecycle),
            &current,
        );
        (current, terminal.screen())
    });
    (handle, SessionTask(task))
}

fn queue_replies(
    terminal: &mut TerminalProbe,
    replies: &mut VecDeque<Vec<u8>>,
    total: &mut usize,
    mode: encoding::Mode,
) -> bool {
    for reply in terminal.take_replies() {
        let Ok(reply) = mode.encode(reply.into_bytes()) else {
            return false;
        };
        if reply.len() > MAX_CHUNK || reply.len() > MAX_REPLIES.saturating_sub(*total) {
            return false;
        }
        *total += reply.len();
        replies.push_back(reply);
    }
    true
}

